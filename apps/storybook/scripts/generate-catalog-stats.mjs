import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { fileURLToPath } from "node:url";

const componentsDirectory = fileURLToPath(new URL("../src/components", import.meta.url));
const outputPath = fileURLToPath(
  new URL("../src/overview/catalog-stats.generated.ts", import.meta.url),
);

const readStoryFiles = (directory) =>
  readdirSync(directory, { withFileTypes: true })
    .flatMap((entry) => {
      const path = join(directory, entry.name);

      return entry.isDirectory() ? readStoryFiles(path) : [path];
    })
    .filter((path) => path.endsWith(".stories.tsx"))
    .sort();

const titlePattern = /\btitle\s*:\s*["'`]([^"'`]+)["'`]/g;
const storyExportPattern = /^export const\s+\w+/gm;

const catalogEntries = readStoryFiles(componentsDirectory).map((path) => {
  const source = readFileSync(path, "utf8");
  const title = [...source.matchAll(titlePattern)]
    .map((match) => match[1])
    .find((candidate) => candidate.startsWith("Componentes/"));

  if (!title) {
    throw new Error(`A story pública não possui um título em Componentes/: ${path}`);
  }

  const variations = source.match(storyExportPattern)?.length ?? 0;

  if (variations === 0) {
    throw new Error(`A story pública não exporta nenhuma variação: ${path}`);
  }

  return { title, variations };
});

const titles = catalogEntries.map(({ title }) => title);
const duplicateTitles = titles.filter((title, index) => titles.indexOf(title) !== index);

if (duplicateTitles.length > 0) {
  throw new Error(`Títulos públicos duplicados: ${[...new Set(duplicateTitles)].join(", ")}`);
}

const catalogStats = {
  components: catalogEntries.length,
  variations: catalogEntries.reduce((total, entry) => total + entry.variations, 0),
};

const source = `// Generated by scripts/generate-catalog-stats.mjs. Do not edit manually.\n\nexport const catalogStats = {\n  components: ${catalogStats.components},\n  variations: ${catalogStats.variations},\n} as const;\n`;

writeFileSync(outputPath, source);
