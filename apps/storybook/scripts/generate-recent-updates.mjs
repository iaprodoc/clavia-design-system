import { execFileSync } from "node:child_process";
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const outputPath = fileURLToPath(
  new URL("../src/overview/recent-updates.generated.ts", import.meta.url),
);
const repositoryRoot = fileURLToPath(new URL("../../../", import.meta.url));

const fallbackUpdates = [{ date: "Não disponível", title: "Catálogo inicial" }];
const skipUpdatePattern = /\[skip-update\]/i;

const formatDate = (value) =>
  new Intl.DateTimeFormat("pt-BR", {
    day: "numeric",
    month: "long",
    year: "numeric",
  }).format(new Date(`${value}T12:00:00Z`));

const toTitle = (subject, body) => {
  const candidate = [subject, ...body.split("\n")].find(
    (line) => line.trim() && !line.startsWith("Merge pull request"),
  );

  const normalized = (candidate ?? subject)
    .trim()
    .replace(/^[a-z]+(?:\([^)]*\))?!?:\s*/i, "")
    .replace(/\s*\(#\d+\)\s*$/, "");

  return normalized
    ? normalized[0].toUpperCase() + normalized.slice(1)
    : "Atualização do Design System";
};

const readRecentUpdates = () => {
  try {
    const output = execFileSync(
      "git",
      [
        "log",
        "--date=short",
        "--format=%ad%x1f%s%x1f%b%x1e",
        "-12",
        "--",
        "apps/storybook",
        "packages/icons",
        "packages/tokens",
        "packages/ui",
      ],
      { cwd: repositoryRoot, encoding: "utf8" },
    );

    const updates = output
      .split("\x1e")
      .map((entry) => entry.trim())
      .filter(Boolean)
      .map((entry) => {
        const [date, subject, body = ""] = entry.split("\x1f");

        return {
          date: formatDate(date),
          title: toTitle(subject, body),
          visible: !skipUpdatePattern.test(subject),
        };
      })
      .filter((update) => update.visible)
      .map(({ visible: _visible, ...update }) => update)
      .slice(0, 3);

    return updates.length > 0 ? updates : fallbackUpdates;
  } catch {
    return fallbackUpdates;
  }
};

const updates = readRecentUpdates();
const [latestUpdate] = updates;

const formatUpdate = (update, indent = "") =>
  `${indent}{\n${indent}  date: ${JSON.stringify(update.date)},\n${indent}  title: ${JSON.stringify(update.title)},\n${indent}}`;

const source = `// Generated by scripts/generate-recent-updates.mjs. Do not edit manually.\n\nexport const latestUpdate = ${formatUpdate(latestUpdate)} as const;\n\nexport const latestUpdates = [\n${updates.map((update) => `${formatUpdate(update, "  ")},`).join("\n")}\n] as const;\n`;

writeFileSync(outputPath, source);
